MASK_CHANNELS = 2
MASK_ROOT = config.Data.SEGMENTED_IMAGES

def to_rgb_uint8(image):
    '''Contert an image into RGB unit8 format.'''
    #read in image
    image = np.asarray(image)
    #convert from Greyscale or RGBA to RGB and ensure image is in unit8 format
    if image.ndim == 2:
        image = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)
    elif image.shape[-1] == 4:
        image = cv2.cvtColor(image, cv2.COLOR_RGBA2RGB)
    if image.dtype != np.uint8:
        image = np.clip(image, 0, 255).astype(np.uint8)
    return image


def clahe(image, clip_limit=2.0, tile=(8, 8)):
    '''Apply CLAHE to an image and return the result
       Param: Image -> np.ndarray: Image to have CLAHE applied
             clip_limit -> Float: Clip limit for CLAHE
             tile -> Tuple: Grid size for CLAHE
       Return: np.ndarray: Image with CLAHE applied
    '''
    gray_image = cv2.cvtColor(to_rgb_uint8(image), cv2.COLOR_RGB2GRAY)
    return cv2.createCLAHE(clipLimit=clip_limit, tileGridSize=tile).apply(gray_image)


def foreground(image):
    '''Extract the foreground of an image using HSV colour and otsu thresholding
        Param: Image -> np.ndarray
        Return: np.ndarray: Binary mask of the foreground
    '''
    hsv = cv2.cvtColor(to_rgb_uint8(image), cv2.COLOR_RGB2HSV)
    saturation = hsv[:, :, 1]
    _, mask = cv2.threshold(saturation, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    return mask

def unet_mask(image_path, size):
    '''Load in a mask that was generated by the unet mdel and return a resized version of it
       Param: Image_path -> Path to original image
              Size -> Tuple of (int, int) for resizing the mask
    '''
    p = Path(image_path)
    #The mask image is stored utilizing following the same structure as original image, but instead within a mask directory
    #All mask names == Image names, only difference is PNG extension instead of original image extension
    mask = cv2.imread(str(MASK_ROOT / p.parent.name / (p.stem + ".png")), cv2.IMREAD_GRAYSCALE)
    if mask is None:
        return None
    return cv2.resize(mask, tuple(size), interpolation=cv2.INTER_AREA)


def mask_from_path(image_path, size=(224, 224), image=None):
    '''
    Load in a mask that was generated from the UNET model and return a resized version of it, along with the foreground channel
    Param: Image_path -> Path to original image
           size -> Tuple of (int,int) for resizing mask and foreground channels
           image -> np.ndarry: optional to original image along with image path
    '''
    #if the image is not loaded, then load in the image
    if image is None:
        image = img_pre.load_image(str(image_path))
    #if image is still None, then return a blank mask
    if image is None:
        return np.zeros((size[1], size[0], MASK_CHANNELS), np.float32)
    #call mask channels to return foreground and mask channels stacked together normalized to a 0-1 range
    return mask_channels(image, unet_mask(image_path, size), size)

def mask_channels(rgb_image, mask_image, size):
    '''
    Take in an RGB image and mask and return a stacked array of the foreground and mask channels
    param: rgb_image -> np.ndarray: original image
           mask_image -> np.ndarray: mask image
           size -> Tuple of (int, int) for resizing mask and foreground channels
    return: np.ndarray: Stacked foreground and mask channels normalized to a 0-1 range
    '''
    #ensure image is in correct format and resize if necessary
    rgb_image = to_rgb_uint8(rgb_image)
    if (rgb_image.shape[1], rgb_image.shape[0]) != tuple(size):
        rgb_image = cv2.resize(rgb_image, tuple(size), interpolation=cv2.INTER_AREA)
    #if there is no mask image, then generate a mask using CLAHE and foreground extraction
    if mask_image is None:
        mask_image = clahe(rgb_image)
    return np.stack([foreground(rgb_image), mask_image], axis=-1).astype(np.float32) / 255.0


def unet_mask_from_image(unet, image, size):
    '''Generate a mask for an image using the UNET model and return a Resized version of it
        UTILIZED FOR PREDICTION MODEL IF NEEDED IF UNET MODEL ACTIVATED
       Param: unet -> UNET model: Model to generate the mask
              image -> np.ndarray: original image to generate mask for
              size -> Tuple of (int, int) for resizing the mask
       return: np.ndarray: Resized mask generated by the unet model
    '''

    #First read in original image and resize to desired formate    
    resized_image = img_pre.resize_image(to_rgb_uint8(image), (384, 384))
    #ensure the image is in correct format for the UNET model and normalize to 0-1 range 
    x = np.asarray(resized_image, np.float32)[None] / 255.0
    #If the Unet model was trained with channels first, then transpose the image to match the input shape of the model
    if unet.input_shape[1] == 3:
        pred = unet.predict(np.transpose(x, (0, 3, 1, 2)), verbose=0)[0, 0]
    else:
        #generate a prediction for the mask using the UNET model and resize to desired size we only need the item of the first batch since this is a single image
        pred = unet.predict(x, verbose=0)[0, ..., 0]
    #resize the image and return
    return cv2.resize((pred * 255).astype(np.uint8), tuple(size), interpolation=cv2.INTER_AREA)


def get_percent_of_Disease(img_path, mask_path):

    '''
    UTILIZED TO GENERATE LABELS FOR THE GBIF DATASET, THIS FUNCTION IS NOT USED NEEDED FOR FINAL CODE
    Calculate the potential percentage of disease on a leaf based on the mask generated by the unet model, and the area of a leaf based on the contours of the image
    param: img_path -> Path to original image
           mask_path -> path to existing mask
    Returm: tuple of (str, str) -> First label determines if a disease is present, and second label determines severity
    '''

    #read in the image and the mnas
    img = cv2.imread(str(img_path))
    mask = cv2.imread(str(mask_path), cv2.IMREAD_GRAYSCALE)

    #crop any potential borders from the image, and resize to standard size
    img = img_pre.crop_border(img)
    img = cv2.resize(img, (384, 384))
    #Convert the mask to a true binary mask and count number of pixels that are diseased
    mask = (mask > 0).astype(np.uint8) * 255
    lesion_pixels = int(np.count_nonzero(mask))

    #convert image to grey for contouring
    gray_Image = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    #reduce noise within the image and apply otsu thresholding to find contours of the leaf
    blurred = cv2.GaussianBlur(gray_Image, (5,5),0)
    _, threshold = cv2.threshold(blurred, 150, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

    #find contours and fill the mask to get the total area of the leaf
    contours, hierarchy = cv2.findContours(threshold, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    filled_mask = np.zeros_like(gray_Image)

    cv2.drawContours(image=filled_mask, contours=contours, contourIdx=-1, color=(255,255,255), thickness=cv2.FILLED)

    #if there are contours, then calculate the total area of the leaf, otherwise return unkown as the plant could not be properly contoured
    if contours:
        area = 0
        for cont in contours:
            area += cv2.contourArea(cont)
    else:
        return ('Unknown', 'UNKNOWN')
    #calculate percentage of diseased area based on total area of leaf and number of pixels that are diseased, return labels based on percentage
    pct_diseased = (lesion_pixels / area) * 100

    if pct_diseased < 15:
        return ('healthy', 'HEALTHY')
    elif  pct_diseased < 40:
        return('disease', 'MILD')
    elif  pct_diseased < 75:
        return('disease', 'MODERATE')
    elif  pct_diseased < 100:
        return('disease', 'SEVERE')
    else:
        return('disease', 'UNKNOWN')

